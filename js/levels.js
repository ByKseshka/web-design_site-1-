// Подсказки перед уровнями (1 слайд)
export function getLevelHint(levelIndex) {
  const l = LEVELS[levelIndex - 1];
  if (!l) return null;
  return {
    duration: 2.5,
    title: `Уровень ${l.index}`,
    name: l.name,
    text: l.hint,
    render: 'level_intro',
    symbol: getLevelSymbol(levelIndex),
  };
}

function getLevelSymbol(levelIndex) {
  const symbols = ['✦', '☯', '⇄', '↑', '◉', '⬢', '✸', '⇄', '◈', '⟐', '☠', '⏳'];
  return symbols[(levelIndex - 1) % symbols.length];
}